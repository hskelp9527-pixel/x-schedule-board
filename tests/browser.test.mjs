import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const extension = fileURLToPath(new URL('..', import.meta.url));
const output = fileURLToPath(new URL('../artifacts/', import.meta.url));
await mkdir(output, { recursive: true });
const profile = await mkdtemp(join(tmpdir(), 'x-schedule-test-'));
const edge = 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const date = new Date(Date.now() + 86400000 * 2);
let snapshot = [{ rest_id: '11', execute_at: date.getTime() / 1000, tweet_request: { status: '从 X 定时列表读取' } }];
const fields = [['Month', date.getMonth()+1],['Day', date.getDate()],['Year', date.getFullYear()],['Hour', 18],['Minute', 30]];
const html = `<!doctype html><html lang="zh"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><body style="margin:0;font:16px system-ui;background:white"><a data-testid="AppTabBar_Profile_Link" href="/me">个人资料</a><h1>模拟 X · 定时发稿</h1><div data-testid="tweetTextarea_0" contenteditable="true">下一篇文章</div><div role="dialog" style="margin:20px;padding:20px;border:1px solid #ddd">${fields.map(([label,value],i)=>`<label id="label${i}">${label}</label><select aria-labelledby="label${i}"><option value="${value}">${value}</option></select>`).join('')}<div><button data-testid="scheduledConfirmationPrimaryAction">Confirm</button></div></div></body></html>`;
let context;
try {
  context = await chromium.launchPersistentContext(profile, { executablePath: process.env.BROWSER_PATH || (existsSync(edge) ? edge : chromium.executablePath()), headless: true, ignoreDefaultArgs: ['--disable-extensions'], args: [`--disable-extensions-except=${extension}`, `--load-extension=${extension}`], viewport: { width: 1100, height: 800 } });
  const worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
  await context.route('https://x.com/**', route => route.fulfill({ contentType: 'text/html; charset=utf-8', body: html }));
  await context.route('https://x.com/i/api/graphql/test/FetchScheduledTweets', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ data: { viewer: { scheduled_tweet_list: snapshot } } }) }));
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('https://x.com/home');
  const board = page.locator('#x-schedule-board');
  await board.locator('.launcher').waitFor();
  await page.locator('[data-xsb-record]').click();
  await board.locator('.item').waitFor();
  assert.match(await board.locator('.badge').textContent(), /手动记录/);
  assert.match(await board.locator('.status').textContent(), /仍需在 X/);
  await page.evaluate(() => fetch('/i/api/graphql/test/FetchScheduledTweets'));
  await page.waitForFunction(() => document.querySelector('#x-schedule-board').shadowRoot.querySelectorAll('.item').length === 2);
  assert.match(await board.locator('.scan-info').textContent(), /1 条/);
  assert.equal(await board.locator('.badge.x').count(), 1);
  snapshot = [];
  await page.evaluate(() => fetch('/i/api/graphql/test/FetchScheduledTweets'));
  await page.waitForFunction(() => document.querySelector('#x-schedule-board').shadowRoot.querySelector('.scan-info').textContent.includes('0 条'));
  assert.match(await board.locator('.list').textContent(), /未在最近的 X 列表中/);
  await board.locator('.add').click();
  const p = n => String(n).padStart(2, '0');
  await board.locator('input[name=at]').fill(`${date.getFullYear()}-${p(date.getMonth()+1)}-${p(date.getDate())}T20:30`);
  await board.locator('textarea').fill('<img src=x onerror=alert(1)> 只显示文本');
  await board.locator('form .primary').click();
  assert.equal(await board.locator('.list img').count(), 0);
  const downloadPromise = page.waitForEvent('download'); await board.locator('.export').click();
  const download = await downloadPromise; assert.match(download.suggestedFilename(), /x-schedule-board-me/);
  await page.screenshot({ path: join(output, 'desktop.png') });
  await page.setViewportSize({ width: 360, height: 740 });
  await page.screenshot({ path: join(output, 'mobile.png') });
  const rect = await board.locator('.panel').boundingBox(); assert(rect.x >= 0 && rect.x + rect.width <= 361);
  await page.evaluate(() => document.querySelector('[data-testid=AppTabBar_Profile_Link]').setAttribute('href','/other'));
  await page.waitForFunction(() => document.querySelector('#x-schedule-board').shadowRoot.querySelector('.account').textContent === '@other');
  assert.equal(await board.locator('.item').count(), 0);
  assert.equal((await worker.evaluate(() => chrome.storage.local.get('entries'))).entries.length, 3);
  await board.locator('.add').click();
  await board.locator('textarea').fill('other 账号的私人草稿');
  // Same task: switch account and submit before the 120ms DOM refresh can run.
  await page.evaluate(() => {
    document.querySelector('[data-testid=AppTabBar_Profile_Link]').setAttribute('href','/third');
    document.querySelector('#x-schedule-board').shadowRoot.querySelector('form').requestSubmit();
  });
  await page.waitForFunction(() => document.querySelector('#x-schedule-board').shadowRoot.querySelector('.account').textContent === '@third');
  assert.equal((await worker.evaluate(() => chrome.storage.local.get('entries'))).entries.length, 3);
  assert.deepEqual(errors, []);
  console.log('Browser verified: selected-time button, passive list scan, empty snapshots, account isolation, backup, safe text, narrow layout');
} finally {
  await context?.close();
  await rm(profile, { recursive: true, force: true });
}
